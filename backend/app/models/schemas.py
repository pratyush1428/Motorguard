from pydantic import BaseModel, Field, field_validator
from typing import Optional, List, Dict, Any
from datetime import datetime

class SensorDataPayload(BaseModel):
    device_id: str = Field(..., description="Unique ESP32 device identifier, e.g. MOTOR-001")
    timestamp: Optional[str] = Field(None, description="ISO-8601 formatted timestamp or generated by server")
    temperature: float = Field(..., description="Motor temperature in °C from DS18B20")
    current: float = Field(..., description="Motor current in Amperes from ACS712 20A")
    vibration: float = Field(..., description="Vibration / acceleration in g from GY-521 MPU6050")
    raw_vib_x: Optional[float] = Field(None, description="Raw X-axis acceleration in g")
    raw_vib_y: Optional[float] = Field(None, description="Raw Y-axis acceleration in g")
    raw_vib_z: Optional[float] = Field(None, description="Raw Z-axis acceleration in g")
    motor_status: Optional[str] = Field("RUNNING", description="RUNNING, WARNING, FAULT, or OFF")
    relay_status: Optional[str] = Field("ACTIVE", description="ACTIVE (motor powered) or INACTIVE (isolated)")
    is_simulated: Optional[bool] = Field(False, description="Flag indicating if data is simulated or real hardware")

    @field_validator('temperature')
    @classmethod
    def validate_temperature(cls, v):
        # Realistic DC motor physical limits: -20°C to 150°C
        if v < -20.0 or v > 150.0:
            raise ValueError(f"Temperature reading {v}°C is physically impossible or disconnected sensor")
        return round(v, 2)

    @field_validator('current')
    @classmethod
    def validate_current(cls, v):
        # ACS712 20A range limit: -25A to +25A, typical motor current >= 0
        if v < -25.0 or v > 25.0:
            raise ValueError(f"Current reading {v}A is outside ACS712 measurement limits")
        return max(0.0, round(v, 3))

    @field_validator('vibration')
    @classmethod
    def validate_vibration(cls, v):
        # MPU6050 typically +/- 2g or +/- 16g. Vibration magnitude cannot be negative.
        if v < 0.0 or v > 20.0:
            raise ValueError(f"Vibration magnitude {v}g is outside valid sensor range")
        return round(v, 3)

class HealthEvaluation(BaseModel):
    health_score: float = Field(..., ge=0, le=100)
    health_status: str = Field(..., description="Healthy (90-100), Warning (70-89), Critical (<70)")
    risk_level: str = Field(..., description="LOW, MODERATE, HIGH, CRITICAL")
    risk_reasons: List[str] = Field(default_factory=list)
    urgency: str = Field("Routine", description="Routine, Scheduled, Immediate")
    recommendation: str = Field(...)
    observation: str = Field(...)
    rate_of_change_temp: float = 0.0
    rate_of_change_current: float = 0.0
    rate_of_change_vib: float = 0.0
    anomalies_detected: List[str] = Field(default_factory=list)

class FaultRecord(BaseModel):
    id: Optional[int] = None
    timestamp: str
    fault_name: str
    severity: str  # NORMAL, WARNING, CRITICAL
    sensor: str
    current_value: float
    threshold: float
    duration_seconds: float
    reason: str
    recommended_action: str
    is_resolved: bool = False

class AlertEvent(BaseModel):
    id: Optional[int] = None
    timestamp: str
    severity: str  # INFO, WARNING, CRITICAL
    parameter: str
    value: float
    threshold: float
    duration: str
    reason: str
    recommended_action: str
    acknowledged: bool = False

class MaintenanceEvent(BaseModel):
    id: Optional[int] = None
    timestamp: str
    event_type: str
    priority: str  # LOW, MEDIUM, HIGH, URGENT
    description: str
    inspection_area: str
    notes: Optional[str] = None
    status: str = "OPEN"  # OPEN, IN_PROGRESS, RESOLVED

class SystemSettings(BaseModel):
    temp_warning: float = 50.0
    temp_critical: float = 65.0
    current_warning: float = 1.80
    current_critical: float = 2.80
    vibration_warning: float = 0.85
    vibration_critical: float = 1.60
    moving_avg_window: int = 10
    alert_duration_seconds: int = 30
    auto_relay_shutdown: bool = True
    refresh_interval_ms: int = 1000
    system_mode: str = "SIMULATION"  # HARDWARE or SIMULATION
    simulation_mode: str = "NORMAL"  # NORMAL, HIGH_VIBRATION, OVERHEATING, OVERLOAD, COMBINED_FAULT, CRITICAL_FAULT

class RelayCommandRequest(BaseModel):
    command: str = Field(..., description="ON or OFF")
    reason: Optional[str] = "Manual operator action"

class EmergencyStopRequest(BaseModel):
    reason: Optional[str] = "Operator triggered manual emergency stop"

